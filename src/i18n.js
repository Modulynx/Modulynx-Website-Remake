const STORE_KEY = 'modulynx-lang';

export function currentLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch { /* storage blocked — fall through */ }
  return document.documentElement.lang === 'en' ? 'en' : 'ar';
}

export function t(key, lang = currentLang()) {
  return (DICT[lang] && DICT[lang][key]) ?? DICT.ar[key] ?? '';
}

export function applyLang(lang) {
  const table = DICT[lang];
  if (!table) return;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  for (const el of document.querySelectorAll('[data-i18n]')) {
    const value = table[el.dataset.i18n];
    if (value != null) el.textContent = value;
  }

  // data-i18n-attr="aria-label:nav.aria|alt:s4.photoAlt"
  for (const el of document.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split('|')) {
      const [attr, key] = pair.split(':');
      const value = table[key];
      if (attr && value != null) el.setAttribute(attr.trim(), value);
    }
  }

  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.textContent = lang === 'ar' ? 'EN' : 'عربي';

  try { localStorage.setItem(STORE_KEY, lang); } catch { /* ignore */ }
}
